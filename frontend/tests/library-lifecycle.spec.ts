import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const token='test-import-token-at-least-32-characters'
const headers={Authorization:`Bearer ${token}`}

test('archive, restore, protected deletion, retained notes and explicit package recovery use real storage',async({page,request},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const packageData=await(await request.get('/api/matches/comeback-1107/package')).json()
  const id='lifecycle-browser-match';packageData.schema_version='pulse-xi-match-package/1'; delete packageData.integrity
  packageData.match.match_id=id;packageData.match.title='Lifecycle research dataset'
  packageData.events.forEach((e:{match_id:string})=>{e.match_id=id})
  expect((await request.post('/api/data-hub/import',{headers,data:packageData})).ok()).toBe(true)
  const pass=packageData.events.find((e:{type:string;match_second:number})=>e.type==='pass'&&e.match_second>500)
  await page.goto(`/#/sandbox?match=${id}&event=${pass.event_id}&at=${pass.match_second}`)
  await expect(page.getByTestId('pass-inspector')).toHaveAttribute('data-event-id',pass.event_id)
  await page.getByLabel('Event note',{exact:true}).fill('Retain this research note even when source is deleted')
  await page.getByRole('button',{name:'Bookmark selected event',exact:true}).click()
  await expect(page.getByRole('list',{name:'Saved event bookmarks'})).toContainText('Retain this research note')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('pulse-xi-workspace-v1')??'{}').eventId)).toBe(pass.event_id)
  await page.getByRole('link',{name:'MATCH DATA HUB',exact:true}).click()
  await page.getByLabel('Import token',{exact:true}).fill(token)
  const card=page.getByRole('article').filter({hasText:id})
  await card.getByRole('button',{name:'Archive match',exact:true}).focus();await page.keyboard.press('Enter')
  const dialog=page.getByRole('dialog',{name:'Confirm dataset operation'})
  await expect(dialog).toContainText(id)
  await dialog.getByRole('button',{name:'Confirm archive',exact:true}).click()
  await expect(card).toHaveCount(0)
  expect((await request.get(`/api/matches/${id}/events?limit=1000`)).ok()).toBe(true)
  await page.getByLabel('Archive status').selectOption('archived')
  await expect(card).toContainText('ARCHIVED')
  await card.getByRole('button',{name:'Open for analysis',exact:true}).click()
  await expect(page.getByLabel('SELECT MATCH')).toHaveValue(id)
  await page.getByRole('slider',{name:'Seek match time'}).fill(String(pass.match_second))
  await expect(page.getByTestId('pass-inspector')).toHaveAttribute('data-event-id',pass.event_id)
  await page.getByRole('link',{name:'MATCH DATA HUB',exact:true}).click()
  await page.getByLabel('Import token',{exact:true}).fill(token)
  await page.getByLabel('Archive status').selectOption('archived')
  await card.getByRole('button',{name:'Restore archived match',exact:true}).click()
  await dialog.getByRole('button',{name:'Confirm restore',exact:true}).click()
  await expect(card).toHaveCount(0)
  await page.getByLabel('Archive status').selectOption('active')
  const download=page.waitForEvent('download');await card.getByRole('button',{name:'Download complete package'}).click()
  const backup=JSON.parse(await readFile(await(await download).path() as string,'utf8'))
  expect(backup.events).toEqual(packageData.events)
  expect(backup.integrity.content_sha256).toMatch(/^[a-f0-9]{64}$/)
  await card.getByRole('button',{name:'Delete imported match',exact:true}).click()
  await expect(dialog.getByRole('button',{name:'Permanently delete match',exact:true})).toBeDisabled()
  await page.getByLabel('Type match ID to delete').fill('wrong-match')
  await expect(dialog.getByRole('button',{name:'Permanently delete match',exact:true})).toBeDisabled()
  await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0)
  await card.getByRole('button',{name:'Delete imported match',exact:true}).click()
  await page.getByLabel('Type match ID to delete').fill(id)
  await dialog.getByRole('button',{name:'Permanently delete match',exact:true}).click()
  await expect(card).toHaveCount(0)
  expect((await request.get(`/api/matches/${id}`)).status()).toBe(404)
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('pulse-xi-workspace-v1')??'{}').matchId)).toBe(id)
  await page.reload()
  await expect(page.getByRole('status').filter({hasText:'Saved or linked match is unavailable'})).toBeVisible()
  const recovery=page.getByRole('region',{name:'Unavailable bookmark recovery'})
  await recovery.getByRole('button',{name:'Check saved sources',exact:true}).click()
  await expect(recovery).toContainText('Retain this research note')
  const notes=page.waitForEvent('download');await recovery.getByRole('button',{name:'Download retained notes',exact:true}).click()
  expect(JSON.parse(await readFile(await(await notes).path() as string,'utf8')).items[0].eventId).toBe(pass.event_id)
  await page.getByLabel('Import token',{exact:true}).fill(token)
  await page.getByLabel('Canonical match JSON').setInputFiles({name:'saved-package.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))})
  await page.getByRole('button',{name:'Validate and preview',exact:true}).click()
  await expect(page.getByLabel('Import preview')).toContainText('This identity was deleted')
  await page.getByRole('button',{name:'Confirm dataset recovery',exact:true}).click()
  await expect(card).toBeVisible()
  expect(await(await request.get(`/api/matches/${id}/events?limit=1000`)).json()).toEqual(packageData.events)
  await page.setViewportSize({width:360,height:800})
  await card.getByRole('button',{name:'Delete imported match',exact:true}).click()
  await expect(dialog).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('delete-confirmation-mobile.png')})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await dialog.getByRole('button',{name:'Cancel operation',exact:true}).click()
  await card.getByRole('button',{name:'Delete imported match',exact:true}).click()
  await page.getByLabel('Type match ID to delete').fill(id)
  await dialog.getByRole('button',{name:'Permanently delete match',exact:true}).click()
  await expect(card).toHaveCount(0)
  await recovery.getByRole('button',{name:'Check saved sources',exact:true}).click()
  await expect(recovery).toContainText('Retain this research note')
  await recovery.getByRole('button',{name:`Remove local reference ${pass.event_id}`,exact:true}).click()
  await recovery.getByRole('button',{name:'Keep note',exact:true}).click()
  await expect(recovery).toContainText('Retain this research note')
  await recovery.getByRole('button',{name:`Remove local reference ${pass.event_id}`,exact:true}).click()
  await recovery.getByRole('button',{name:'Confirm remove local reference',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('pulse-xi-bookmarks-v1')??'{}').items.length)).toBe(0)
  expect(errors).toEqual([])
})

test('stale revisions and invalid authorization cannot delete a different or newer dataset',async({page,request})=>{
  const packet=await(await request.get('/api/matches/high-press-2209/package')).json()
  packet.schema_version='pulse-xi-match-package/1'; delete packet.integrity;const id='lifecycle-stale';packet.match.match_id=id
  packet.events.forEach((e:{match_id:string})=>e.match_id=id)
  expect((await request.post('/api/data-hub/import',{headers,data:packet})).ok()).toBe(true)
  await page.goto('/#/data');await page.getByLabel('Import token',{exact:true}).fill(token)
  const card=page.getByRole('article').filter({hasText:id})
  await card.getByRole('button',{name:'Delete imported match',exact:true}).click()
  const current=(await(await request.get('/api/data-hub')).json()).matches.find((m:{match:{match_id:string}})=>m.match.match_id===id)
  expect((await request.post(`/api/data-hub/matches/${id}/lifecycle`,{headers,data:{action:'archive',confirm_match_id:id,generation:current.lifecycle.generation,revision:current.lifecycle.revision}})).ok()).toBe(true)
  await page.getByLabel('Type match ID to delete').fill(id)
  await page.getByRole('button',{name:'Permanently delete match',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('dataset changed')
  expect((await request.get(`/api/matches/${id}`)).status()).toBe(200)
  await page.getByLabel('Archive status').selectOption('archived')
  await page.getByLabel('Import token',{exact:true}).fill('wrong')
  await card.getByRole('button',{name:'Restore archived match',exact:true}).click()
  await page.getByRole('button',{name:'Confirm restore',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Import authorization required')
  await expect(card).toContainText('ARCHIVED')
})
