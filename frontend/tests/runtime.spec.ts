test('unauthorized operator stays signed out and duplicate pending creation is disabled', async ({ page }) => {
  await page.goto('/#/runtime')
  await page.getByLabel('Operator access token').fill('wrong-token-with-more-than-32-characters')
  await page.getByRole('button', { name: 'Connect operator' }).click()
  await expect(page.getByRole('alert')).toContainText('unauthorized')
  await page.getByLabel('Operator access token').fill(token)
  await page.getByRole('button', { name: 'Connect operator' }).click()
  await expect(page.getByRole('button', { name: 'Disconnect operator' })).toBeVisible()
  if (await page.getByLabel('Runtime / branch').inputValue()) await expect(page.getByLabel('Authoritative match clock')).toBeVisible()
  if (!await page.getByRole('button', { name: 'Create authoritative scenario' }).isVisible()) await page.getByText('Scenario builder', { exact: true }).click()
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let calls = 0
  const previous = await page.getByLabel('Runtime / branch').inputValue()
  await page.route('**/api/sandbox/scenarios', async route => {
    if (route.request().method() === 'POST') { calls++; await gate }
    await route.continue()
  })
  await page.getByRole('button', { name: 'Create authoritative scenario' }).click()
  await expect(page.getByRole('button', { name: 'Create authoritative scenario' })).toBeDisabled()
  release()
  await expect(page.getByLabel('Runtime / branch')).not.toHaveValue(previous)
  await expect(page.getByLabel('Authoritative match clock')).toHaveText('00:00')
  expect(calls).toBe(1)
})

test('an active run is recovered after refresh and can be paused without clock drift', async ({ page, request }) => {
  const sid = await create(page, 120)
  await page.getByLabel('Server progression rate').selectOption('1')
  await page.getByRole('button', { name: 'Run on server', exact: true }).click()
  await expect.poll(async () => (await (await request.get(`/api/sandbox/sessions/${sid}/state`, { headers })).json()).tick).toBeGreaterThan(0)
  await page.reload()
  await page.getByLabel('Operator access token').fill(token)
  await page.getByRole('button', { name: 'Connect operator' }).click()
  await expect(page.getByText('Server run: running')).toBeVisible()
  await page.getByRole('button', { name: 'Pause engine', exact: true }).click()
  await expect(page.getByText('Server run: cancelled')).toBeVisible()
  const stopped = await (await request.get(`/api/sandbox/sessions/${sid}/state`, { headers })).json()
  expect(stopped.state.lifecycle).toBe('paused')
  // Wait for multiple driver passes using a real server read, never a fake clock.
  await expect.poll(async () => (await (await request.get(`/api/sandbox/sessions/${sid}/runs`, { headers })).json())[0].status).toBe('cancelled')
  const after = await (await request.get(`/api/sandbox/sessions/${sid}/state`, { headers })).json()
  expect(after.state_hash).toBe(stopped.state_hash)
})
