test('stale revision and interrupted response reconcile without double-applying a step', async ({ page, request }) => {
  const sid = await create(page)
  await page.getByLabel('Step seconds').fill('10')
  let failed = false
  await page.route(`**/api/sandbox/sessions/${sid}/commands`, async route => {
    if (!failed) {
      failed = true
      const response = await route.fetch()
      expect(response.ok()).toBeTruthy()
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { code: 'transaction_failed' } }) })
    } else await route.continue()
  })
  await page.getByRole('button', { name: 'Step engine', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('transaction_failed')
  await page.getByRole('button', { name: 'Retry original operation safely' }).click()
  await expect(page.getByLabel('Authoritative match clock')).toHaveText('00:10')
  const state = await (await request.get(`/api/sandbox/sessions/${sid}/state`, { headers })).json()
  expect(state.revision).toBe(1)
  await page.unroute(`**/api/sandbox/sessions/${sid}/commands`)
  await page.route(`**/api/sandbox/sessions/${sid}/commands`, async route => {
    const body = route.request().postDataJSON()
    await request.post(`/api/sandbox/sessions/${sid}/commands`, { headers, data: { operation_id: 'external-race-' + sid.slice(-16), expected_revision: body.expected_revision, kind: 'step', ticks: 1 } })
    await route.continue()
  })
  await page.getByRole('button', { name: 'Step engine', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('stale_revision')
  await page.getByRole('button', { name: 'Reload current revision' }).click()
  await expect(page.getByLabel('Authoritative match clock')).toHaveText('00:11')
})

