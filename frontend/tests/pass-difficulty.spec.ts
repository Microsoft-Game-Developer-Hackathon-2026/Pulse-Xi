import { expect, test } from '@playwright/test'

test('selects a real pass, exposes its calculation, and removes future evidence on seek', async ({ page, request }, testInfo) => {
  const base = '/api/matches/comeback-1107'
  const response = await request.get(`${base}/pass-difficulty?at_second=5400`)
  const list = await response.json()
  const pass = list.items.find((item: { team_id: string }) => item.team_id === 'harbour')
  expect(pass).toBeTruthy()
  await page.goto('/')
  await page.getByRole('slider', { name: 'Seek match time' }).fill('5400')
  const selector = page.getByRole('combobox', { name: /SELECT PASS/ })
  await expect(selector).toBeVisible()
  await selector.selectOption(pass.event_id)
  const inspector = page.getByTestId('pass-inspector')
  await expect(inspector).toHaveAttribute('data-event-id', pass.event_id)
  await expect(inspector.getByRole('meter')).toHaveAttribute('value', String(pass.score))
  await page.getByText('Inspect calculation and source evidence', { exact: true }).click()
  await expect(page.getByText(pass.formula_version, { exact: false })).toBeVisible()
  const evidence = await request.get(`${base}/passes/${pass.event_id}/difficulty/evidence?at_second=${pass.match_second}`)
  expect((await evidence.json()).verified).toBe(true)
  await inspector.screenshot({ path: testInfo.outputPath('pass-inspector.png') })
  await page.getByRole('slider', { name: 'Seek match time' }).fill(String(pass.match_second - 1))
  await expect(page.locator(`[data-testid="pass-inspector"][data-event-id="${pass.event_id}"]`)).toHaveCount(0)
  await expect(page.locator(`option[value="${pass.event_id}"]`)).toHaveCount(0)
  await page.getByRole('slider', { name: 'Seek match time' }).fill('0')
  await expect(page.getByText('No passes recorded for this team at the selected time.')).toBeVisible()
})

test('pass analysis recovers from API failure and fits a mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/pass-difficulty?*', route => route.fulfill({ status: 503, body: '{}' }))
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Retry pass analysis' })).toBeVisible()
  await page.unroute('**/pass-difficulty?*')
  await page.getByRole('button', { name: 'Retry pass analysis' }).click()
  await expect(page.getByText('No passes recorded for this team at the selected time.')).toBeVisible()
  await page.getByRole('slider', { name: 'Seek match time' }).fill('5400')
  await expect(page.getByTestId('pass-inspector')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBe(true)
  await page.getByRole('combobox', { name: /PASS FILTER/ }).selectOption('high-complete')
  await expect(page.getByText(/No passes meet this filter/)).toBeVisible()
})

test('favorite-player lens shows a backend-calculated sample summary', async ({ page, request }) => {
  const data = await (await request.get('/api/matches/comeback-1107/pass-difficulty/players')).json()
  const player = data.players.find((item: { sample_count: number }) => item.sample_count > 0)
  await page.goto('/')
  await page.getByRole('slider', { name: 'Seek match time' }).fill('5400')
  await page.getByLabel('VIEW').selectOption('favorite_player')
  await page.getByLabel('FANDNA / RECAP: FOLLOW PLAYER', { exact: true }).selectOption(player.player_id)
  await expect(page.locator('.pass-player-summary')).toContainText(`${player.sample_count} rated passes`)
  await page.getByRole('slider', { name: 'Seek match time' }).fill('0')
  await expect(page.locator('.pass-player-summary')).toContainText('No rated pass summary available')
})
